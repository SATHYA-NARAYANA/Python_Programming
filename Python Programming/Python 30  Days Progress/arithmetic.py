# Python Arithmetic operations
'''
    We use Variables to store data like a real world objects.

    To store water we need some think like a container. Variables is similar to container. IN that variable we can able to store different data. 
'''
x = int(input("Enter a value to x :"))
y = int(input("Enter a value to y :"))


print (f"   Arithmetic Operation Addition(+)             : {x + y}")
print (f"   Arithmetic Operation Subtraction(-)          : {x - y}")
print (f"   Arithmetic Operation Multiplication(*)       : {x * y}")
print (f"   Arithmetic Operation Division(/)             : {x / y}")
print (f"   Arithmetic Operation Modulus(%)              : {x % y}")
print (f"   Arithmetic Operation Exponential(**)         : {x ** y}")
print (f"   Arithmetic Operation Floor division(//)      : {x // y}")
